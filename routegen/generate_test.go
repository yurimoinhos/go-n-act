func TestGenerateRoundTrip(t *testing.T) {
	mod := t.TempDir()
	routes := filepath.Join(mod, "routes")
	writeFixture(t, mod, routes, repoRoot(t))

	files, err := Generate(context.Background(), Options{Dir: routes})
	if err != nil {
		t.Fatal(err)
	}
	indexGen := string(mustGen(t, files, "routes/clients/index.gen.ts"))
	if !strings.Contains(indexGen, "export interface ListInInput") || strings.Contains(indexGen, "actor") {
		t.Fatalf("input type leaked or missing:\n%s", indexGen)
	}
	if !strings.Contains(indexGen, `"admin" | "user"`) || !strings.Contains(indexGen, "updated: string") {
		t.Fatalf("types:\n%s", indexGen)
	}
	if !strings.Contains(indexGen, `call<ListOut>("route.clients.index.v1", "Loader"`) {
		t.Fatalf("client:\n%s", indexGen)
	}
	if !strings.Contains(indexGen, "Loader lists clients.") {
		t.Fatalf("doc:\n%s", indexGen)
	}
	idGen := string(mustGen(t, files, "routes/clients/param_id.gen.ts"))
	if !strings.Contains(idGen, "id: string") || !strings.Contains(idGen, `call<GetOut>("route.clients.param_id.v1", "Get"`) {
		t.Fatalf("get client:\n%s", idGen)
	}
	register := string(mustGen(t, files, "routes/clients/register.gen.go"))
	if !strings.Contains(register, "Loader") || !strings.Contains(register, "Get") || strings.Contains(register, "Format") {
		t.Fatalf("register:\n%s", register)
	}
	root := string(mustGen(t, files, "routes/register.gen.go"))
	if !strings.Contains(root, "func RegisterAll(") || !strings.Contains(root, "example.com/app/routes/clients") {
		t.Fatalf("root register:\n%s", root)
	}
	tree := string(mustGen(t, files, "routes/routeTree.gen.tsx"))
	for _, want := range []string{"./clients/index.scss", "ClientsIndexRoute", "ClientsParamIdRoute", "ClientsRouteRoute", "<Outlet />", `"./clients/$id"`} {
		if !strings.Contains(tree, want) {
			t.Fatalf("tree missing %s:\n%s", want, tree)
		}
	}
	for path := range files {
		if strings.Contains(filepath.ToSlash(path), "helpers") {
			t.Fatalf("generated a helper route %s", path)
		}
	}

	if err := Write(routes, files, false); err != nil {
		t.Fatal(err)
	}
	if err := Write(routes, files, true); err != nil {
		t.Fatal(err)
	}
	stale := filepath.Join(routes, "clients", "index.gen.ts")
	if err := os.WriteFile(stale, []byte("// Code generated by routegen. DO NOT EDIT.\nexport const stale = true;\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := Write(routes, files, true); err == nil || !strings.Contains(err.Error(), "index.gen.ts") {
		t.Fatalf("check err = %v", err)
	}
	if err := Write(routes, files, false); err != nil {
		t.Fatal(err)
	}

	tidy := exec.Command("go", "mod", "tidy")
	tidy.Dir = mod
	if out, err := tidy.CombinedOutput(); err != nil {
		t.Fatalf("tidy: %v\n%s", err, out)
	}
	test := exec.Command("go", "test", "./routes/clients/")
	test.Dir = mod
	if out, err := test.CombinedOutput(); err != nil {
		t.Fatalf("go test: %v\n%s", err, out)
	}
}

func TestGenerateRejectsDollarDirectory(t *testing.T) {
	dir := t.TempDir()
	routes := filepath.Join(dir, "routes")
	writeFile(t, filepath.Join(routes, "clients", "$id", "route.go"), "package id\n")
	_, err := Generate(context.Background(), Options{Dir: routes})
	if err == nil || !strings.Contains(err.Error(), "clients/param_id/route.go") || strings.Contains(err.Error(), "go.mod") {
		t.Fatal(err)
	}
}

